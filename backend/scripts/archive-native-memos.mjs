/** Archive only the four public native acceptance commands from an existing
 * UFVK-only scan. This script reads no keys and performs no network or send action.
 * Run: node --import tsx backend/scripts/archive-native-memos.mjs SCAN_JSON VAULTS_DIR
 */
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { verifyReceiptHex } from '../../src/evidence/verifyReceipt.ts';

const [scanPath, vaultsDir] = process.argv.slice(2);
assert.ok(scanPath && vaultsDir, 'Pass the completed scanner JSON and original source vault directory');
const scan = JSON.parse(await readFile(scanPath, 'utf8'));
const rawScan = `${JSON.stringify(scan)}\n`;
const acceptance = JSON.parse(await readFile('docs/evidence/native-live-acceptance.json', 'utf8'));
assert.equal(scan.adapter, 'testnet-chain');
assert.equal(scan.network, 1);
assert.equal(scan.complete, true);
assert.ok(scan.blocks.length > 0);
const expectedTransactions = new Set(acceptance.transactions.map(tx => tx.txid));
let previous = null;
for (const block of scan.blocks) {
  if (previous) {
    assert.equal(block.height, previous.height + 1);
    assert.equal(block.previous_hash_hex, previous.hash_hex);
  }
  for (const tx of block.transactions) assert.ok(expectedTransactions.has(tx.txid_hex), 'Refuse to publish unrelated wallet transactions');
  previous = block;
}
const records = [];
for (const tx of acceptance.transactions) {
  const matches = scan.blocks.flatMap(block => block.transactions.filter(item => item.txid_hex === tx.txid).map(item => ({ block, item })));
  assert.equal(matches.length, 1, 'A recorded transaction must appear exactly once');
  const { block, item } = matches[0];
  assert.equal(block.height, tx.blockHeight);
  assert.equal(item.outputs.length, 1, 'Expected one registry memo output');
  const output = item.outputs[0];
  const result = verifyReceiptHex(output.memo_hex);
  assert.equal(result.valid, true, result.errorMessage);
  const scenario = tx.label.startsWith('release_') ? 'release' : 'cancel';
  const acceptedVault = acceptance.vaults.find(vault => vault.scenario === scenario);
  assert.equal(result.switchIdHex, acceptedVault.switchId);
  const vaultPath = resolve(vaultsDir, acceptedVault.switchId);
  const manifest = JSON.parse(await readFile(resolve(vaultPath, 'manifest.json'), 'utf8'));
  assert.equal(result.manifestDigestHex, manifest.manifestDigestHex);
  assert.equal(result.sourcePubKeyHex, manifest.sourcePubKeyHex);
  const command = JSON.parse(await readFile(resolve(vaultPath, 'commands', `command-${result.sequence.padStart(20, '0')}.json`), 'utf8'));
  assert.equal(command.memoHex, output.memo_hex, 'Scanned bytes must exactly match the original durable command');
  records.push({ label: tx.label, operation: result.operation, sequence: result.sequence, requestedExpiryHeight: result.requestedExpiryHeight, txid: tx.txid,
    blockHeight: block.height, blockHash: block.hash_hex, transactionIndex: item.tx_index, outputIndex: output.output_index,
    memoHex: output.memo_hex, switchIdHex: result.switchIdHex, manifestDigestHex: result.manifestDigestHex,
    sourcePubKeyHex: result.sourcePubKeyHex, originalJournalMatch: true });
}
assert.equal(records.length, 4);
const report = { version: 1, capturedAt: new Date().toISOString(), network: 'testnet',
  provenance: { method: 'Fresh broadcast-free UFVK-only scan using wallet-gate scan-batch', indexer: 'https://testnet.zec.rocks:443',
    scanStartHeight: scan.blocks[0].height, expectedPreviousHash: scan.blocks[0].previous_hash_hex,
    scanEndHeight: scan.confirmed_through, observedTipHeight: scan.observed_tip_height, requestedConfirmations: 3,
    rawScanSha256: createHash('sha256').update(rawScan).digest('hex'), rawScanFile: 'native-live-memo-scan.json', rawScanEncoding: 'UTF-8 compact JSON followed by LF; normalize CRLF to LF before hashing',
    checks: ['continuous block heights and previous hashes', 'exact recorded txid and inclusion height', 'strict 512-byte format and Ed25519 signature', 'acceptance switch and original manifest/source-key binding', 'byte-for-byte original durable journal match'],
    scope: 'Scanner evidence binds decrypted memos to the transactions returned by the configured indexer. Browser signature verification is independent of that scan but is not a transaction-inclusion proof or independent consensus verification. No spending key or viewing key is published.' }, records };
await writeFile('docs/evidence/native-live-memo-scan.json', rawScan);
await writeFile('docs/evidence/native-live-memos.json', `${JSON.stringify(report, null, 2)}\n`);
await writeFile('src/evidence/nativeMemos.ts', `// Generated by backend/scripts/archive-native-memos.mjs from a completed viewing-only scan.\n// Public fixture commands only; no private or viewing keys. Tests compare the public archive.\nexport const NATIVE_MEMO_RECEIPTS = ${JSON.stringify(records, null, 2)} as const;\n`);
console.log(`Archived ${records.length} original native memos; signatures, context, journals and recorded inclusion all matched.`);
