/** Compile docs/assets/press.css for the static landing page from the app's design-system files. */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const parts = ['src/styles/press.css', 'src/styles/overview.css', 'docs/assets/landing-press.src.css'];
let css = '/* Generated by scripts/build-landing-css.mjs. Edit the source files instead. */\n';
for (const part of parts) {
  const text = (await readFile(resolve(root, part), 'utf8')).replace(/^@import\s+["']tailwindcss["'];\s*/m, '');
  css += `\n/* ${part} */\n${text}`;
}
await writeFile(resolve(root, 'docs/assets/press.css'), css);
console.log(`Wrote docs/assets/press.css from ${parts.length} files.`);
