/** Publish only an already-built Vite browser bundle under docs/app for GitHub Pages. */
import { cp, mkdir, readFile, readdir, lstat, realpath, rename, rm, writeFile } from 'node:fs/promises';
import { dirname, resolve, relative, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomUUID } from 'node:crypto';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = resolve(root, 'dist');
const docs = resolve(root, 'docs');
const destination = resolve(docs, 'app');
const marker = '.canary-generated-site.json';

function within(parent, child) {
  const value = relative(parent, child);
  return value !== '' && value !== '..' && !value.startsWith(`..${sep}`) && !value.startsWith(sep);
}
async function exists(path) {
  try { return await lstat(path); } catch (error) { if (error.code === 'ENOENT') return null; throw error; }
}
async function rejectLinks(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = resolve(directory, entry.name);
    if (!within(source, path)) throw new Error('Source asset escaped dist.');
    if (entry.isSymbolicLink()) throw new Error(`Build assets must not contain symbolic links: ${relative(source, path)}`);
    if (entry.isDirectory()) await rejectLinks(path);
  }
}

// Validate all inputs and exact output boundaries before replacing generated content.
if (!within(root, source) || !within(root, destination) || destination !== resolve(root, 'docs', 'app')) throw new Error('Unexpected public-demo output directory.');
if ((await lstat(source)).isSymbolicLink() || (await lstat(docs)).isSymbolicLink()) throw new Error('dist and docs must be real directories, not links.');
const realRoot = await realpath(root);
if (!within(realRoot, await realpath(source)) || !within(realRoot, await realpath(docs))) throw new Error('Build paths resolve outside the repository.');
const index = await readFile(resolve(source, 'index.html'), 'utf8');
if (!index.includes('assets/') || /(?:src|href)=["']\/assets\//.test(index)) {
  throw new Error('Build the app first with npm run build -- --base=./; docs/app needs relative asset URLs.');
}
await rejectLinks(source);
const current = await exists(destination);
if (current) {
  if (current.isSymbolicLink() || !current.isDirectory()) throw new Error('docs/app must be a generated directory, not a link or file.');
  if (!within(await realpath(docs), await realpath(destination))) throw new Error('docs/app resolves outside docs.');
  let ownership;
  try { ownership = JSON.parse(await readFile(resolve(destination, marker), 'utf8')); } catch { throw new Error('Refusing to replace an unmarked docs/app directory. Check its contents first.'); }
  if (ownership.generator !== 'canary-public-demo') throw new Error('docs/app was not generated by this script.');
}

const stage = resolve(docs, `.canary-app-stage-${randomUUID()}`);
const backup = resolve(docs, `.canary-app-backup-${randomUUID()}`);
if (!within(docs, stage) || !within(docs, backup)) throw new Error('Invalid staging paths.');
await mkdir(stage);
try {
  await cp(source, stage, { recursive: true, dereference: false, errorOnExist: false });
  await writeFile(resolve(stage, marker), JSON.stringify({ generator: 'canary-public-demo', source: 'dist', output: 'docs/app', version: 1 }, null, 2) + '\n');
  if (current) await rename(destination, backup);
  try { await rename(stage, destination); }
  catch (error) { if (current) await rename(backup, destination); throw error; }
  // Both exact absolute paths were validated above; only generated staging/backup content is removed.
  if (current) await rm(backup, { recursive: true, force: true });
  console.log(`Copied the browser-only build to ${destination}`);
  console.log('docs/index.html remains the watch page; no native wallet or local state is copied.');
} finally {
  if (within(docs, stage) && (await exists(stage))) await rm(stage, { recursive: true, force: true });
}
